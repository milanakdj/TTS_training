def write_card(api, code, dry):
    title, hours, rate, shape, prov = CARDS[code]
    body = CARD.format(title=title, hours=hours, rate=rate, shape=shape, prov=prov,
                       prefix=REPO_PREFIX)
    if dry: return
    path = f"{STAGE}/README-{code}.md"
    open(path, "w").write(body)
    api.upload_file(path_or_fileobj=path, path_in_repo="README.md", repo_id=repo_of(code),
                    repo_type="dataset", commit_message="Card")

SCHEMA = pa.schema([
    ("id", pa.string()),
    ("audio", pa.struct([("bytes", pa.binary()), ("path", pa.string())])),
    ("text", pa.string()),
    ("duration", pa.float32()),
    ("spk", pa.string()),
    ("src", pa.string()),
    ("sr", pa.int32()),
    ("ch", pa.int8()),
    ("nspk", pa.int16()),
    ("lang_sec", pa.string()),
    ("segments", pa.string()),
    ("dnsmos", pa.float32()),
    ("snr_db", pa.float32()),
])

def h16(s: str) -> str: return hashlib.sha256(s.encode()).hexdigest()[:16]
def h12(s: str) -> str: return hashlib.sha256(s.encode()).hexdigest()[:12]

def resolve(p: str | None):
    if not p: return None
    for c in (p, p.replace("/projects/data/ttsteam/proc_data_new/", f"{ROOT}/"),
              p.replace("/projects/data/ttsteam/", "/workspace/")):
        if os.path.isfile(c): return c
    return None

def archived_paths() -> set[str]:
    """Exact audio paths already in nepali-speech-archive -- 30,042 of the
    indicvoices-r-long files are there, so they must not be uploaded twice."""
    s = set()
    if os.path.isfile(ARCHIVE_IDMAP):
        with open(ARCHIVE_IDMAP, errors="replace") as f:
            for l in f:
                try: s.add(json.loads(l)["path"])
                except Exception: pass
    return s

def flac_bytes(src: str, off, dur, target_sr=None):
    """FLAC for one row. Rows carrying an offset name a whole episode -- one is
    28,422 s -- so those are cut, never read whole."""
    cmd = ["ffmpeg", "-nostdin", "-v", "error"]
    if off is not None and dur:
        cmd += ["-ss", f"{float(off):.3f}", "-t", f"{float(dur):.3f}"]
    cmd += ["-i", src]
    if target_sr: cmd += ["-ar", str(target_sr)]
    cmd += ["-c:a", "flac", "-compression_level", "5", "-f", "flac", "pipe:1"]
    p = subprocess.run(cmd, capture_output=True)
    return p.stdout if p.returncode == 0 and p.stdout else None

def row_of(d: dict, code: str, dirname: str):
    src = resolve(d.get("audio_filepath"))
    if not src: return None, None
    text = d.get("text") or d.get("normalised_text") or d.get("unnormalised_text")
    if not text or not str(text).strip(): return None, None       # no transcript, no upload
    off = d.get("offset") if d.get("offset") is not None else d.get("chunk_start_s")
    dur = float(d.get("duration") or 0)
    if dur <= 0: return None, None
    chunk_id = d.get("id") or d.get("key") or d.get("sample_id")
    uid = h16(f"{src}#{off if off is not None else 0}")
    spk_label = d.get("speaker_id") or (d.get("speakers") or [None])[0] or os.path.dirname(src)
    ls = d.get("language_seconds")
    segs = d.get("asr_segments") or d.get("turns")
    rec = dict(id=uid, text=str(text), duration=dur, spk=h12(f"{dirname}|{spk_label}"),
               src=code, sr=int(d.get("sample_rate") or 0), ch=int(d.get("channels") or 1),
               nspk=int(d.get("num_speakers") or 0),
               lang_sec=json.dumps(ls, ensure_ascii=False) if ls else None,
               segments=json.dumps(segs, ensure_ascii=False) if segs else None,
               dnsmos=d.get("dnsmos_ovrl_mean"), snr_db=d.get("snr_estimate_db"))
    return rec, dict(src_path=src, off=off, chunk_id=str(chunk_id) if chunk_id else None)

def main(a):
    if a.list:
        for c, d, mf, h in SOURCES: print(f"{c}  {d:28} ~{h:8.1f} h  {ROOT}/{d}/{mf}")
        return
    want = set(a.sources.split(",")) if a.sources else {c for c, *_ in SOURCES}
    os.makedirs(STAGE, exist_ok=True)
    api = HfApi(token=open("/root/.hf_milanakdj").read().strip())
    st_path = f"{STAGE}/state.json"
    st = json.load(open(st_path)) if os.path.isfile(st_path) else {"shards": {}, "srcs": {}, "ids": []}
    done_ids = set(st.get("ids", []))
    arch = archived_paths()
    print(f"[init] repos={REPO_PREFIX}-r1..r6 dry_run={a.dry_run} archived_paths={len(arch):,} "
          f"resume_shards={st['shards']} seen_ids={len(done_ids):,}", flush=True)

    buf, nbytes, cur = [], 0, None
    idmap = open(NEW_IDMAP, "a")

    def flush():
        nonlocal buf, nbytes
        if not buf or cur is None: return
        shard = st["shards"].get(cur, 0)
        repo = repo_of(cur)
        path = f"{STAGE}/train-{shard:05d}.parquet"
        pq.write_table(pa.Table.from_pylist(buf, schema=SCHEMA), path, compression="zstd")
        mb = os.path.getsize(path) / 1e6
        if a.dry_run:
            print(f"[shard] {os.path.basename(path)} {len(buf)} rows {mb:.0f} MB (kept, dry run)", flush=True)
        else:
            for attempt in range(4):
                try:
                    api.upload_file(path_or_fileobj=path, path_in_repo=f"data/{os.path.basename(path)}",
                                    repo_id=repo, repo_type="dataset",
                                    commit_message=f"shard {shard:05d}")
                    break
                except Exception as e:
                    print(f"[retry {attempt}] {type(e).__name__}: {str(e)[:200]}", flush=True)
                    time.sleep(30 * (attempt + 1))
            else:
                sys.exit(f"upload failed after retries: {path}")
            os.remove(path)
            print(f"[shard] {repo.split('/')[-1]} data/{os.path.basename(path)} "
                  f"{len(buf)} rows {mb:.0f} MB", flush=True)
        st["shards"][cur] = shard + 1
        buf, nbytes = [], 0
        st["ids"] = sorted(done_ids)
        json.dump(st, open(st_path, "w"))

    for code, dirname, mf, hours in SOURCES:
        if code not in want: continue
        path = f"{ROOT}/{dirname}/{mf}"
        if not os.path.isfile(path): print(f"!! {code} {dirname}: no manifest", flush=True); continue
        cur = code
        start = st["srcs"].get(code, 0)
        print(f"\n[src] {code} -> {repo_of(code)}  ~{hours} h  resume_line={start:,}", flush=True)
        if not a.dry_run:
            api.create_repo(repo_of(code), repo_type="dataset", private=False, exist_ok=True)
            api.update_repo_settings(repo_id=repo_of(code), repo_type="dataset", gated="manual")
            write_card(api, code, a.dry_run)
        kept = skipped = 0
        with open(path, errors="replace") as f, ThreadPoolExecutor(WORKERS) as pool:
            pending = []
            for lineno, line in enumerate(f):
                if lineno < start: continue
                if not NE.search(line): continue
                try: d = json.loads(line)
                except Exception: continue
                rec, loc = row_of(d, code, dirname)
                if not rec: skipped += 1; continue
                if loc["src_path"] in arch: skipped += 1; continue
                if rec["id"] in done_ids or (loc["chunk_id"] and loc["chunk_id"] in done_ids):
                    skipped += 1; continue
                done_ids.add(rec["id"])
                if loc["chunk_id"]: done_ids.add(loc["chunk_id"])
                pending.append((rec, loc, pool.submit(flac_bytes, loc["src_path"], loc["off"], rec["duration"], a.sr)))
                if len(pending) >= WORKERS * 4 or a.limit and kept + len(pending) >= a.limit:
                    for rec, loc, fut in pending:
                        b = fut.result()
                        if not b: skipped += 1; continue
                        rec["audio"] = {"bytes": b, "path": f"{rec['id']}.flac"}
                        buf.append(rec); nbytes += len(b); kept += 1
                        idmap.write(json.dumps({"id": rec["id"], "src": code,
                                                "path": loc["src_path"], "off": loc["off"]}) + "\n")
                    pending = []; idmap.flush()
                    st["srcs"][code] = lineno + 1
                    if nbytes >= SHARD_BYTES: flush()
                    if kept % 2000 < WORKERS * 4:
                        # st["shards"][code], not `shard` -- that name is local to
                        # flush(). The single-repo version had it in this scope; the
                        # split to six repos moved it and left this print unbound,
                        # which is a NameError the first time kept reaches 2000.
                        print(f"   {code} line {lineno:,} kept {kept:,} skipped {skipped:,} "
                              f"buf {nbytes/1e6:.0f} MB shard {st['shards'].get(code, 0)}",
                              flush=True)
                if a.limit and kept >= a.limit: break
            for rec, loc, fut in pending:
                b = fut.result()
                if not b: continue
                rec["audio"] = {"bytes": b, "path": f"{rec['id']}.flac"}
                buf.append(rec); nbytes += len(b); kept += 1
                # This tail drain must write id_map too. It did not, so the last
                # partial batch of every source was uploaded with no provenance
                # entry -- 14 rows of r3 and 15 of r4 went up untraceable. The
                # mapping is the only way back from an opaque id to a source path,
                # so a silent hole in it defeats the point of the opaque codes.
                idmap.write(json.dumps({"id": rec["id"], "src": code,
                                        "path": loc["src_path"], "off": loc["off"]}) + "\n")
            idmap.flush()
        flush()                     # never mix two sources in one shard
        print(f"[src] {code} done: kept {kept:,} skipped {skipped:,} "
              f"shards {st['shards'].get(code, 0)}", flush=True)
        json.dump(st, open(st_path, "w"))
    flush()
    idmap.close()
    if not a.dry_run:
        for code in want:
            i = api.dataset_info(repo_of(code), expand=["gated"])
            print(f"  {repo_of(code)}  gated={i.gated}  shards={st['shards'].get(code, 0)}", flush=True)
    print("[done]", flush=True)

if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--sources"); p.add_argument("--limit", type=int)
    p.add_argument("--sr", type=int, help="resample everything to this rate (omit to keep native)")
    p.add_argument("--dry-run", action="store_true"); p.add_argument("--list", action="store_true")
    main(p.parse_args())
