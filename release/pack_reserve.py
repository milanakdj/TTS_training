#!/usr/bin/env python3
"""Package the Nepali audio that is neither public nor in nepali-speech-archive,
and stream it to a second gated repo one shard at a time.

Why a streaming packager rather than `datasets.push_to_hub`: the largest source is
6,680 h of 48 kHz chunks, so the FLAC never fits on a staging disk at once. Each
shard is encoded, uploaded and deleted before the next begins, and `state.json`
records the manifest line reached, so a kill -9 costs one shard.

Source names are NOT uploaded. `src` carries an opaque code; the code -> directory
mapping lives only in dataset/SOURCE_CODES.md, the way id_map.jsonl already holds
the archive's id -> path mapping.

  python3 pack_reserve.py --list
  python3 pack_reserve.py --sources r3 --limit 40 --dry-run
  python3 pack_reserve.py --sources r1,r2,r3,r4,r5,r6
"""
from __future__ import annotations
import argparse, hashlib, io, json, os, re, subprocess, sys, time
from concurrent.futures import ThreadPoolExecutor

import pyarrow as pa
import pyarrow.parquet as pq
from huggingface_hub import HfApi

ROOT = "/workspace/proc_data_new"
STAGE = "/workspace/hf_stage_reserve"
REPO_PREFIX = os.environ.get("RESERVE_PREFIX", "milanakdj/nepali-audio-reserve")
def repo_of(code: str) -> str: return f"{REPO_PREFIX}-{code}"
ARCHIVE_IDMAP = "/root/tts/TTS_training/release/id_map.jsonl"
NEW_IDMAP = "/root/tts/TTS_training/release/id_map_reserve.jsonl"
SHARD_BYTES = int(os.environ.get("SHARD_BYTES", 900_000_000))
WORKERS = int(os.environ.get("PACK_WORKERS", 4))
NE = re.compile(r'"language": ?"(ne|nep|nepali|Nepali)"|/Nepali/')

